#!/bin/sh
# Assemble the 68000 savestate stub into ss68k_stub_rom.sv, the ROM ss_m68k
# reads it from (512 words, NOP after the code). A module rather than a
# $readmemh file, so neither Quartus nor Verilator has to find a data file.
# The .sv is committed, so the core builds without an assembler.
set -e
root=$(cd "$(dirname "$0")/.." && pwd)
dir="$root/src/NeoGeo Cart/core/NeoGeoCore/savestate"
tmp=$(mktemp -d)
m68k-elf-as -m68000 --register-prefix-optional -o "$tmp/stub.o" "$dir/ss68k_stub.s"
m68k-elf-objcopy -O binary -j .text "$tmp/stub.o" "$tmp/stub.bin"
python3 -I - "$tmp/stub.bin" "$dir/ss68k_stub_rom.sv" <<'EOF'
import sys
code = open(sys.argv[1], "rb").read()
words = 512
if len(code) > words * 2 or len(code) % 2:
    sys.exit(f"stub is {len(code)} bytes, more than {words * 2} or odd")
with open(sys.argv[2], "w") as f:
    f.write("// Generated by tools/build_stub.sh from ss68k_stub.s: do not edit.\n")
    f.write("module ss68k_stub_rom(input clk, input [9:1] addr, output reg [15:0] q);\n")
    f.write("\talways @(posedge clk)\n\t\tcase (addr)\n")
    for i in range(0, len(code), 2):
        f.write(f"\t\t\t9'h{i // 2:03x}: q <= 16'h{code[i] << 8 | code[i + 1]:04x};\n")
    f.write("\t\t\tdefault: q <= 16'h4e71;\t// NOP\n\t\tendcase\nendmodule\n")
print(f"stub: {len(code)} bytes of code")
EOF
m68k-elf-objdump -d "$tmp/stub.o" | sed -n '/<entry>/,$p'
rm -rf "$tmp"
